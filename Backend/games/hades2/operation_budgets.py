"""Finite timeout components used by Hades II aggregate host watchdogs.

Update the maximum subprocess counts whenever prepare/restore add another
bounded command. The count is the audited longest branch, not the number of
commands in a typical run.
"""

SUBPROCESS_TIMEOUT_SECONDS = 30
PREPARATION_MAX_SUBPROCESS_CALLS = 16
RESTORE_MAX_SUBPROCESS_CALLS = 6
PROCESS_QUERY_TIMEOUT_SECONDS = 5
LAUNCH_TIMEOUT_SECONDS = 10

LLDB_MODULE_PATH_TIMEOUT_SECONDS = 10
LLDB_DISCOVERY_TIMEOUT_SECONDS = 5
LLDB_PYTHON_TIMEOUT_SECONDS = 8

LUA_BOUNDARY_TIMEOUT_SECONDS = 3
LUA_EXPRESSION_TIMEOUT_SECONDS = 2
LUA_CLEANUP_TIMEOUT_SECONDS = 3
REPLAY_EXPRESSION_TIMEOUT_SECONDS = 5
TRAIT_TRAY_HANDOFF_TIMEOUT_SECONDS = 0.75

DEFAULT_COMMAND_TIMEOUT_SECONDS = 6.0
SAVE_EDITOR_OPERATION_BUDGET_SECONDS = 25
SAVE_EDITOR_OPEN_BUDGET_SECONDS = PROCESS_QUERY_TIMEOUT_SECONDS + SAVE_EDITOR_OPERATION_BUDGET_SECONDS
MAILBOX_COMMAND_BUDGET_SECONDS = 2 * LUA_EXPRESSION_TIMEOUT_SECONDS + TRAIT_TRAY_HANDOFF_TIMEOUT_SECONDS

POST_PREPARATION_SCAN_BUDGET_SECONDS = SUBPROCESS_TIMEOUT_SECONDS + PROCESS_QUERY_TIMEOUT_SECONDS
LAUNCH_OPERATION_BUDGET_SECONDS = LAUNCH_TIMEOUT_SECONDS + POST_PREPARATION_SCAN_BUDGET_SECONDS
PREPARATION_OPERATION_BUDGET_SECONDS = (
    PREPARATION_MAX_SUBPROCESS_CALLS * SUBPROCESS_TIMEOUT_SECONDS + POST_PREPARATION_SCAN_BUDGET_SECONDS
)
RESTORE_OPERATION_BUDGET_SECONDS = (
    RESTORE_MAX_SUBPROCESS_CALLS * SUBPROCESS_TIMEOUT_SECONDS
    + SUBPROCESS_TIMEOUT_SECONDS
    + PROCESS_QUERY_TIMEOUT_SECONDS
)
STATUS_CHECK_BUDGET_SECONDS = 2 * (
    LUA_BOUNDARY_TIMEOUT_SECONDS + LUA_EXPRESSION_TIMEOUT_SECONDS + 2 * LUA_CLEANUP_TIMEOUT_SECONDS
)
STATUS_COMMAND_BUDGET_SECONDS = STATUS_CHECK_BUDGET_SECONDS + REPLAY_EXPRESSION_TIMEOUT_SECONDS
LOAD_PROFILE_OPERATION_BUDGET_SECONDS = STATUS_CHECK_BUDGET_SECONDS + STATUS_COMMAND_BUDGET_SECONDS
DISABLE_ALL_OPERATION_BUDGET_SECONDS = POST_PREPARATION_SCAN_BUDGET_SECONDS + STATUS_CHECK_BUDGET_SECONDS
DISCONNECT_OPERATION_BUDGET_SECONDS = (
    LUA_BOUNDARY_TIMEOUT_SECONDS + LUA_EXPRESSION_TIMEOUT_SECONDS + LUA_CLEANUP_TIMEOUT_SECONDS
)
CONNECT_ATTACH_HEADROOM_SECONDS = 28
CONNECT_OPERATION_BUDGET_SECONDS = (
    POST_PREPARATION_SCAN_BUDGET_SECONDS + STATUS_CHECK_BUDGET_SECONDS + REPLAY_EXPRESSION_TIMEOUT_SECONDS
)
DIAGNOSTICS_OPERATION_BUDGET_SECONDS = (
    SUBPROCESS_TIMEOUT_SECONDS
    + STATUS_CHECK_BUDGET_SECONDS
    + LLDB_DISCOVERY_TIMEOUT_SECONDS
    + LLDB_PYTHON_TIMEOUT_SECONDS
)
